using System.Globalization;
using System.IO.Compression;
using System.Runtime.InteropServices;
using System.Text;
using System.Xml.Linq;
using SkiaSharp;

namespace Fidelity;

/// <summary>
/// Reads the 54 preset patterns (a:pattFill) from PowerPoint's own rendering of the fills deck: PowerPoint draws
/// them as 8×8 device-pixel tiles aligned to the slide. Writes src/Engine/Drawing/PatternPresets.g.cs.
/// </summary>
public static class PatternHarvest
{
    static readonly XNamespace A = "http://schemas.openxmlformats.org/drawingml/2006/main";
    static readonly XNamespace P = "http://schemas.openxmlformats.org/presentationml/2006/main";

    public static void Run()
    {
        const string deck = "generated/fills";
        const int slide = 4;
        XDocument xml;
        using (var zip = ZipFile.OpenRead(Repo.DeckFile(deck)))
        using (var stream = zip.GetEntry($"ppt/slides/slide{slide}.xml")!.Open())
            xml = XDocument.Load(stream);

        using var codec = SKCodec.Create(Path.Combine(References.Dir(deck), $"slide-{slide:000}.png"));
        var info = new SKImageInfo(codec.Info.Width, codec.Info.Height, SKColorType.Rgba8888, SKAlphaType.Unpremul);
        using var bitmap = SKBitmap.Decode(codec, info);
        var pixels = new byte[info.Width * info.Height * 4];
        Marshal.Copy(bitmap.GetPixels(), pixels, 0, pixels.Length);

        var code = new StringBuilder();
        code.AppendLine("// Generated by `dotnet run --project tools/Fidelity -- harvest-patterns` from PowerPoint's rendering of");
        code.AppendLine("// tests/corpus/pptx/generated/fills.pptx (slide 4). Do not edit by hand.");
        code.AppendLine("namespace Engine.Drawing;");
        code.AppendLine();
        code.AppendLine("/// <summary>The preset patterns as 8×8 tiles aligned to the slide; bit 7 of a row byte is the leftmost pixel.</summary>");
        code.AppendLine("public static partial class PatternPresets");
        code.AppendLine("{");
        code.AppendLine("    public static readonly IReadOnlyDictionary<string, byte[]> Tiles = new Dictionary<string, byte[]>");
        code.AppendLine("    {");

        var inconsistent = 0;
        foreach (var sp in xml.Descendants(P + "sp"))
        {
            var preset = (string?)sp.Descendants(A + "pattFill").FirstOrDefault()?.Attribute("prst");
            var xfrm = sp.Descendants(A + "xfrm").FirstOrDefault();
            if (preset == null || xfrm == null)
                continue;
            var off = xfrm.Element(A + "off")!;
            var ext = xfrm.Element(A + "ext")!;
            var x0 = (int)Math.Ceiling((long)off.Attribute("x")! / 9525.0) + 3;
            var y0 = (int)Math.Ceiling((long)off.Attribute("y")! / 9525.0) + 3;
            var x1 = (int)Math.Floor(((long)off.Attribute("x")! + (long)ext.Attribute("cx")!) / 9525.0) - 3;
            var y1 = (int)Math.Floor(((long)off.Attribute("y")! + (long)ext.Attribute("cy")!) / 9525.0) - 3;

            var votes = new int[8, 8, 2];
            for (var y = y0; y < y1; y++)
            {
                for (var x = x0; x < x1; x++)
                {
                    var i = (y * info.Width + x) * 4;
                    var dark = (pixels[i] + pixels[i + 1] + pixels[i + 2]) / 3 < 128 ? 1 : 0;
                    votes[y % 8, x % 8, dark]++;
                }
            }

            var rows = new byte[8];
            for (var r = 0; r < 8; r++)
            {
                for (var c = 0; c < 8; c++)
                {
                    if (votes[r, c, 1] > votes[r, c, 0])
                        rows[r] |= (byte)(0x80 >> c);
                    if (Math.Min(votes[r, c, 0], votes[r, c, 1]) > 0)
                        inconsistent++;
                }
            }
            code.AppendLine($"        [\"{preset}\"] = [{string.Join(", ", rows.Select(b => "0x" + b.ToString("X2", CultureInfo.InvariantCulture)))}],");
        }
        code.AppendLine("    };");
        code.AppendLine("}");

        var target = Path.Combine(Repo.Root, "src", "Engine", "Drawing", "PatternPresets.g.cs");
        File.WriteAllText(target, code.ToString());
        Console.WriteLine($"Wrote {target}; inconsistent tile pixels: {inconsistent} (0 = every pattern is slide-aligned)");
    }
}
