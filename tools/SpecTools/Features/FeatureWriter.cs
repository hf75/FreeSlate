using System.Text;
using SpecTools.Catalog;

namespace SpecTools.Features;

/// <summary>Writes a checked feature catalog as Markdown (for people) and JSON (for tools).</summary>
public static class FeatureWriter
{
    const int MaxSpecRefs = 6;

    public static void Write(FeatureReport report, string yamlFile)
    {
        var doc = report.Document;
        var basePath = Path.Combine(FeatureCommand.FeatureDir, doc.Document);
        File.WriteAllText(basePath + ".md", Markdown(report, yamlFile));
        Json.Write(basePath + ".json", new
        {
            doc.Document,
            doc.Title,
            Coverage = new { Universe = report.Universe.Count, Assigned = report.Universe.Count - report.Unassigned.Count, report.Unassigned },
            Features = report.Features.Select(f => new
            {
                f.Feature.Id,
                Area = f.Area.Id,
                f.Feature.Title,
                f.Feature.Description,
                f.Feature.Priority,
                f.Feature.Difficulty,
                f.Feature.Status,
                f.Feature.Strategy,
                f.Feature.Office,
                f.Elements,
                Spec = f.Spec,
                OfficeNotes = f.OfficeNotes,
            }),
        });
    }

    static string Markdown(FeatureReport report, string yamlFile)
    {
        var doc = report.Document;
        var md = new StringBuilder();
        var features = report.Features;
        var assigned = report.Universe.Count - report.Unassigned.Count;

        md.AppendLine($"# {doc.Title}: feature catalog");
        md.AppendLine();
        md.AppendLine($"Level 2 of the feature catalog. Curated by hand in [{yamlFile}]({yamlFile}); this page is generated by");
        md.AppendLine("`dotnet run --project tools/SpecTools -- features`. Element names link to the format catalog (level 1).");
        md.AppendLine();
        if (doc.Description != null)
        {
            md.AppendLine(doc.Description.Trim());
            md.AppendLine();
        }

        md.AppendLine("## Summary");
        md.AppendLine();
        md.AppendLine($"- {features.Count} features in {doc.Areas.Count} areas");
        md.AppendLine($"- Coverage: {assigned:N0} of the {report.Universe.Count:N0} elements that can occur in a {doc.Document.ToUpperInvariant()} file " +
                      $"({100.0 * assigned / Math.Max(1, report.Universe.Count):F1} %) are assigned to a feature" +
                      (report.Unassigned.Count > 0 ? "; see [unassigned elements](#unassigned-elements)" : ""));
        md.AppendLine();
        md.AppendLine("Priority: **P0** needed for typical documents, **P1** common, **P2** occasional, **P3** rare or editor-only.");
        md.AppendLine("Difficulty: **1** direct mapping to HTML/CSS/SVG … **5** research project.");
        md.AppendLine();
        md.AppendLine("| Area | Features | P0 | P1 | P2 | P3 | Ø difficulty | Partial | Done |");
        md.AppendLine("|---|---:|---:|---:|---:|---:|---:|---:|---:|");
        foreach (var area in doc.Areas)
        {
            var list = features.Where(f => f.Area == area).ToList();
            int P(string p) => list.Count(f => f.Feature.Priority == p);
            md.AppendLine($"| [{area.Title}](#{area.Id}) | {list.Count} | {P("P0")} | {P("P1")} | {P("P2")} | {P("P3")} | " +
                          $"{(list.Count == 0 ? 0 : list.Average(f => f.Feature.Difficulty)):F1} | {list.Count(f => f.Feature.Status == "partial")} | {list.Count(f => f.Feature.Status == "done")} |");
        }
        md.AppendLine($"| **Total** | **{features.Count}** | **{Count(features, "P0")}** | **{Count(features, "P1")}** | **{Count(features, "P2")}** | **{Count(features, "P3")}** | " +
                      $"**{(features.Count == 0 ? 0 : features.Average(f => f.Feature.Difficulty)):F1}** | **{features.Count(f => f.Feature.Status == "partial")}** | **{features.Count(f => f.Feature.Status == "done")}** |");
        md.AppendLine();

        foreach (var area in doc.Areas)
        {
            md.AppendLine($"<a id=\"{area.Id}\"></a>");
            md.AppendLine();
            md.AppendLine($"## {area.Title}");
            md.AppendLine();
            if (area.Description != null)
            {
                md.AppendLine(area.Description.Trim());
                md.AppendLine();
            }
            md.AppendLine("| Feature | Priority | Difficulty | Status | Elements | Office notes |");
            md.AppendLine("|---|---|---|---|---:|---:|");
            foreach (var f in features.Where(f => f.Area == area))
                md.AppendLine($"| [{f.Feature.Title}](#{f.Feature.Id}) | {f.Feature.Priority} | {Dots(f.Feature.Difficulty)} | {f.Feature.Status} | {f.Elements.Count} | {f.OfficeNotes.Count} |");
            md.AppendLine();

            foreach (var f in features.Where(f => f.Area == area))
            {
                md.AppendLine($"<a id=\"{f.Feature.Id}\"></a>");
                md.AppendLine();
                md.AppendLine($"### {f.Feature.Title}");
                md.AppendLine();
                md.AppendLine($"`{f.Feature.Id}` · {f.Feature.Priority} · difficulty {f.Feature.Difficulty} · {f.Feature.Status}");
                md.AppendLine();
                if (f.Feature.Description != null)
                {
                    md.AppendLine(f.Feature.Description.Trim());
                    md.AppendLine();
                }
                if (f.Feature.Strategy != null)
                {
                    md.AppendLine($"**Rendering:** {f.Feature.Strategy.Trim()}");
                    md.AppendLine();
                }
                if (f.Feature.Office != null)
                {
                    md.AppendLine($"**Office behaviour:** {f.Feature.Office.Trim()}");
                    md.AppendLine();
                }
                if (f.Elements.Count > 0)
                {
                    md.AppendLine($"**Elements ({f.Elements.Count}):** {string.Join(", ", f.Elements.Select(ElementLink))}");
                    md.AppendLine();
                }
                if (f.Spec.Count > 0)
                {
                    var refs = f.Spec.Take(MaxSpecRefs).Select(Ref);
                    var more = f.Spec.Count > MaxSpecRefs ? $" and {f.Spec.Count - MaxSpecRefs} more" : "";
                    md.AppendLine($"**Specification:** {string.Join("; ", refs)}{more}");
                    md.AppendLine();
                }
                if (f.OfficeNotes.Count > 0)
                {
                    md.AppendLine($"**MS-OI29500:** {string.Join(", ", f.OfficeNotes)}");
                    md.AppendLine();
                }
            }
        }

        md.AppendLine("<a id=\"unassigned-elements\"></a>");
        md.AppendLine();
        md.AppendLine("## Unassigned elements");
        md.AppendLine();
        if (report.Unassigned.Count == 0)
        {
            md.AppendLine($"None: every element that can occur in a {doc.Document.ToUpperInvariant()} file belongs to at least one feature.");
        }
        else
        {
            md.AppendLine("Elements that can occur in the file format but belong to no feature yet:");
            md.AppendLine();
            foreach (var group in report.Unassigned.GroupBy(e => e[..e.IndexOf(':')]))
                md.AppendLine($"- **{group.Key}** ({group.Count()}): {string.Join(", ", group.Select(ElementLink))}");
        }
        md.AppendLine();

        if (report.OutsideUniverse.Count > 0)
        {
            md.AppendLine("## Assigned but outside the universe");
            md.AppendLine();
            md.AppendLine("Referenced by a feature but not reachable from the universe definition (check the roots):");
            md.AppendLine();
            md.AppendLine(string.Join(", ", report.OutsideUniverse.Select(ElementLink)));
            md.AppendLine();
        }
        return md.ToString();
    }

    static int Count(List<ResolvedFeature> features, string priority) => features.Count(f => f.Feature.Priority == priority);

    static string Dots(int difficulty) => new string('●', difficulty) + new string('○', 5 - difficulty);

    static string ElementLink(string name)
    {
        var prefix = name[..name.IndexOf(':')];
        var anchor = new string(name.ToLowerInvariant().Where(ch => char.IsLetterOrDigit(ch) || ch is '-' or '_').ToArray());
        return $"[`{name}`](../format/namespaces/{prefix}.md#{anchor})";
    }

    static string Ref(SpecRef r)
    {
        var doc = r.Doc switch { "ECMA-376-1" => "", "ECMA-376-4" => "Part 4 ", _ => r.Doc + " " };
        return $"{doc}§{r.Section} {r.Title} (p.{r.Page})";
    }
}
