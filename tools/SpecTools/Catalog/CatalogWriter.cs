using System.Globalization;
using System.Text;
using SpecTools.Pdf;

namespace SpecTools.Catalog;

/// <summary>Everything the catalog command produces, ready to be written.</summary>
public sealed record CatalogData(
    List<NamespaceEntry> Namespaces,
    SpecIndex Spec,
    List<PresetGeometry> PresetShapes,
    List<PresetGeometry> TextWarps,
    List<string> ArtBorders,
    List<string> ShapeTypeValues,
    List<string> TextShapeTypeValues,
    HashSet<string> LinkedOfficeNotes,
    List<string> CompileErrors,
    List<string> Errata,
    int SchemaFiles,
    List<(string Name, string Version)> SourceVersions);

/// <summary>Writes the format catalog as JSON (for tools) and Markdown (for people).</summary>
public static class CatalogWriter
{
    static string FormatDir => Path.Combine(Repo.Catalog, "format");
    static string NamespaceDir => Path.Combine(FormatDir, "namespaces");
    static string SpecDir => Path.Combine(Repo.Catalog, "spec");

    public static void Write(CatalogData data)
    {
        Directory.CreateDirectory(NamespaceDir);
        foreach (var stale in Directory.GetFiles(NamespaceDir))
            File.Delete(stale);

        foreach (var ns in data.Namespaces)
        {
            Json.Write(Path.Combine(NamespaceDir, ns.Prefix + ".json"), ns);
            File.WriteAllText(Path.Combine(NamespaceDir, ns.Prefix + ".md"), NamespacePage(ns));
        }

        Json.Write(Path.Combine(FormatDir, "summary.json"), data.Namespaces.Select(ns => new
        {
            ns.Prefix, ns.Uri, ns.Area, ns.InScope, ns.OfficeVersion, ns.Source, ns.Counts,
        }));
        Json.Write(Path.Combine(FormatDir, "preset-geometries.json"), new { shapes = data.PresetShapes, textWarps = data.TextWarps });
        Json.Write(Path.Combine(FormatDir, "field-codes.json"), data.Spec.FieldCodes.Select(f => new
        {
            f.Name, f.Section, f.Page, OfficeNotes = data.Spec.OfficeNotes.Where(n => n.Part == 1 && n.IsoSection == f.Section).Select(n => n.Section).ToList(),
        }));
        File.WriteAllText(Path.Combine(FormatDir, "README.md"), Overview(data));
        File.WriteAllText(Path.Combine(FormatDir, "preset-geometries.md"), PresetPage(data));
        File.WriteAllText(Path.Combine(FormatDir, "field-codes.md"), FieldCodePage(data));

        Directory.CreateDirectory(SpecDir);
        foreach (var (doc, outline) in data.Spec.Outlines)
            Json.Write(Path.Combine(SpecDir, $"outline-{doc.ToLowerInvariant()}.json"), outline.Select(e => new { e.Level, e.Title, e.Page }));
        Json.Write(Path.Combine(SpecDir, "ms-oi29500-sections.json"), data.Spec.OfficeNotes);
    }

    static string Overview(CatalogData data)
    {
        var md = new StringBuilder();
        var inScope = data.Namespaces.Where(n => n.InScope).ToList();
        var extensions = inScope.Where(IsExtension).ToList();
        var outOfScope = data.Namespaces.Where(n => !n.InScope).ToList();

        md.AppendLine("# Format catalog");
        md.AppendLine();
        md.AppendLine("Generated by `tools/SpecTools` from the specifications in `spec/`. Do not edit by hand; regenerate with");
        md.AppendLine("`dotnet run --project tools/SpecTools -- all`.");
        md.AppendLine();
        md.AppendLine("This is level 1 of the feature catalog: everything the file formats can express, derived from the XML schemas");
        md.AppendLine("and linked to the specification text and to Microsoft's implementation notes. Level 2 (curated features,");
        md.AppendLine("rendering strategy, priorities) builds on it.");
        md.AppendLine();

        md.AppendLine("## Sources");
        md.AppendLine();
        md.AppendLine("| Source | Version | Used for |");
        md.AppendLine("|---|---|---|");
        md.AppendLine("| ECMA-376 Part 1 | 5th edition, December 2016 | section index, field codes, preset geometries, art borders |");
        md.AppendLine("| ECMA-376 Part 2 | 5th edition, December 2021 | OPC schemas |");
        md.AppendLine("| ECMA-376 Part 4 | 5th edition, December 2016 | transitional schemas (what Office writes), section index |");
        foreach (var (name, version) in data.SourceVersions)
            md.AppendLine($"| [{name}] | {version} | {(name == "MS-OI29500" ? "Office implementation notes per ISO/IEC 29500 section" : "Office extension schemas (Appendix A), section index")} |");
        md.AppendLine("| Open XML SDK `data/namespaces.json` | main | namespace prefixes, Office version per namespace |");
        md.AppendLine();

        md.AppendLine("## At a glance");
        md.AppendLine();
        md.AppendLine("In scope are DOCX, PPTX and everything they share (DrawingML, charts, SmartArt, math, VML, packages).");
        md.AppendLine("Attributes are counted per element: an attribute that three elements accept counts three times.");
        md.AppendLine();
        md.AppendLine("| | In scope | thereof Office extensions | SpreadsheetML (out of scope) |");
        md.AppendLine("|---|---:|---:|---:|");
        void Line(string label, Func<NamespaceEntry, int> value) =>
            md.AppendLine($"| {label} | {N(inScope.Sum(value))} | {N(extensions.Sum(value))} | {N(outOfScope.Sum(value))} |");
        Line("Namespaces", _ => 1);
        Line("Elements", n => n.Counts!.Elements);
        Line("Attributes", n => n.Counts!.Attributes + n.Counts.GlobalAttributes);
        Line("Complex types", n => n.Counts!.ComplexTypes);
        Line("Simple types", n => n.Counts!.SimpleTypes);
        Line("Enumeration values", n => n.Counts!.EnumValues);
        Line("Linked specification sections", n => n.Counts!.SpecSections);
        Line("Linked MS-OI29500 sections", n => n.Counts!.OfficeNotes);
        md.AppendLine();

        md.AppendLine("## By area");
        md.AppendLine();
        md.AppendLine("| Area | Namespaces | Elements | Attributes | Complex types | Simple types | Enum values | Spec sections | Office notes |");
        md.AppendLine("|---|---:|---:|---:|---:|---:|---:|---:|---:|");
        foreach (var area in data.Namespaces.GroupBy(n => n.Area))
        {
            var c = area.Select(n => n.Counts!).ToList();
            md.AppendLine($"| {area.Key} | {area.Count()} | {N(c.Sum(x => x.Elements))} | {N(c.Sum(x => x.Attributes + x.GlobalAttributes))} | {N(c.Sum(x => x.ComplexTypes))} | {N(c.Sum(x => x.SimpleTypes))} | {N(c.Sum(x => x.EnumValues))} | {N(c.Sum(x => x.SpecSections))} | {N(c.Sum(x => x.OfficeNotes))} |");
        }
        md.AppendLine();

        md.AppendLine("## Beyond the schemas");
        md.AppendLine();
        md.AppendLine("Some features are not visible in the schemas at all: they are strings with their own syntax (fields),");
        md.AppendLine("data files (preset geometries, art borders) or rules in the specification text.");
        md.AppendLine();
        md.AppendLine("| What | Count | Details |");
        md.AppendLine("|---|---:|---|");
        md.AppendLine($"| Preset shapes (`a:prstGeom`) | {data.ShapeTypeValues.Count} | {Defined(data.ShapeTypeValues, data.PresetShapes)}, see [preset-geometries.md](preset-geometries.md) |");
        md.AppendLine($"| Preset text warps / WordArt (`a:prstTxWarp`) | {data.TextShapeTypeValues.Count} | {Defined(data.TextShapeTypeValues, data.TextWarps)}, see [preset-geometries.md](preset-geometries.md) |");
        md.AppendLine($"| Field codes (Word fields such as PAGE, TOC, REF) | {data.Spec.FieldCodes.Count} | [field-codes.md](field-codes.md) |");
        md.AppendLine($"| Art page borders (images, Part 1 Annex F) | {data.ArtBorders.Count} | `spec/ecma-376/part1/art-borders/` |");
        md.AppendLine($"| MS-OI29500 sections (Office implementation notes) | {N(data.Spec.OfficeNotes.Count)} | {N(data.LinkedOfficeNotes.Count)} linked to catalog entries; all in `catalog/spec/ms-oi29500-sections.json` |");
        md.AppendLine();

        md.AppendLine("## Namespaces");
        md.AppendLine();
        md.AppendLine("| Prefix | Namespace | Area | Since | Elements | Attributes | Simple types | Enum values | Source |");
        md.AppendLine("|---|---|---|---|---:|---:|---:|---:|---|");
        foreach (var ns in data.Namespaces)
        {
            var c = ns.Counts!;
            md.AppendLine($"| [{ns.Prefix}](namespaces/{ns.Prefix}.md) | `{ns.Uri}` | {ns.Area} | {Version(ns.OfficeVersion)} | {N(c.Elements)} | {N(c.Attributes + c.GlobalAttributes)} | {N(c.SimpleTypes)} | {N(c.EnumValues)} | {Cell(ns.Source)} |");
        }
        md.AppendLine();

        md.AppendLine("## Schema compilation");
        md.AppendLine();
        if (data.CompileErrors.Count == 0)
        {
            md.AppendLine($"All {data.SchemaFiles} schema files compile together without errors.");
        }
        else
        {
            md.AppendLine($"{data.CompileErrors.Count} errors while compiling the {data.SchemaFiles} schema files:");
            md.AppendLine();
            foreach (var error in data.CompileErrors)
                md.AppendLine($"- {error}");
        }
        md.AppendLine();
        md.AppendLine("Errata applied to the published schemas:");
        md.AppendLine();
        foreach (var fix in data.Errata)
            md.AppendLine($"- {fix}");
        md.AppendLine();
        md.AppendLine("Shims compiled along with the schemas but not part of the catalog (see `Catalog/Shims.cs`):");
        md.AppendLine();
        foreach (var shim in Shims.All)
            md.AppendLine($"- {shim.Description}");
        return md.ToString();
    }

    static string NamespacePage(NamespaceEntry ns)
    {
        var md = new StringBuilder();
        var c = ns.Counts!;
        md.AppendLine($"# {ns.Prefix}: {ns.Area}");
        md.AppendLine();
        md.AppendLine($"`{ns.Uri}`");
        md.AppendLine();
        md.AppendLine($"- Source: {ns.Source}");
        md.AppendLine($"- Office version: {Version(ns.OfficeVersion)}");
        md.AppendLine($"- In scope: {(ns.InScope ? "yes" : "no")}");
        md.AppendLine();
        md.AppendLine("| Elements | Attributes | Global attributes | Complex types | Simple types | Enum values | Spec sections | Office notes |");
        md.AppendLine("|---:|---:|---:|---:|---:|---:|---:|---:|");
        md.AppendLine($"| {N(c.Elements)} | {N(c.Attributes)} | {N(c.GlobalAttributes)} | {N(c.ComplexTypes)} | {N(c.SimpleTypes)} | {N(c.EnumValues)} | {N(c.SpecSections)} | {N(c.OfficeNotes)} |");
        md.AppendLine();
        md.AppendLine($"Full detail (content models, attribute types, defaults): [{ns.Prefix}.json]({ns.Prefix}.json)");
        md.AppendLine();

        if (ns.Elements.Count > 0)
        {
            md.AppendLine("## Elements");
            md.AppendLine();
            md.AppendLine("| Element | Type | Attributes | Children | Parents | Specification |");
            md.AppendLine("|---|---|---:|---:|---:|---|");
            foreach (var e in ns.Elements)
                md.AppendLine($"| [`{e.Name}`](#{Anchor(e.Name)}){(e.Global == true ? " ◆" : "")} | {Cell(string.Join(", ", e.Types.Select(Code)))} | {e.Attributes.Count} | {e.Children.Count} | {e.Parents.Count} | {Cell(Refs(e.Spec))} |");
            md.AppendLine();
            md.AppendLine("◆ declared globally (can be the root element of a part)");
            md.AppendLine();
        }

        if (ns.GlobalAttributes.Count > 0)
        {
            md.AppendLine("## Global attributes");
            md.AppendLine();
            md.AppendLine("Attributes this namespace adds to elements of other namespaces.");
            md.AppendLine();
            md.AppendLine("| Attribute | Type | Specification |");
            md.AppendLine("|---|---|---|");
            foreach (var a in ns.GlobalAttributes)
                md.AppendLine($"| `{a.Name}` | {Cell(Code(a.Type))}{(a.Values != null ? ": " + Cell(Values(a.Values)) : "")} | {Cell(Refs(a.Spec ?? []))} |");
            md.AppendLine();
        }

        if (ns.SimpleTypes.Count > 0)
        {
            md.AppendLine("## Simple types");
            md.AppendLine();
            md.AppendLine("| Simple type | Definition | Values | Specification |");
            md.AppendLine("|---|---|---|---|");
            foreach (var t in ns.SimpleTypes)
            {
                var facets = t.Facets == null ? "" : string.Join(", ", t.Facets.Select(f => $"{f.Key} `{f.Value}`"));
                var values = t.Values != null ? Values(t.Values) : facets;
                md.AppendLine($"| `{t.Name}` | {Cell(t.Definition)} | {Cell(values)} | {Cell(Refs(t.Spec ?? []))} |");
            }
            md.AppendLine();
        }

        if (ns.Elements.Count > 0)
        {
            md.AppendLine("## Element details");
            md.AppendLine();
            foreach (var e in ns.Elements)
            {
                md.AppendLine($"### {e.Name}");
                md.AppendLine();
                md.AppendLine($"- Type: {string.Join(", ", e.Types.Select(Code))}{(e.Text != null ? $" (text: {Code(e.Text)})" : "")}");
                if (e.Attributes.Count > 0)
                    md.AppendLine($"- Attributes: {string.Join(", ", e.Attributes.Select(a => Code(a.Name) + (a.Required == true ? "!" : "")))}");
                if (e.Children.Count > 0)
                    md.AppendLine($"- Children: {string.Join(", ", e.Children.Select(Code))}");
                if (e.Parents.Count > 0)
                    md.AppendLine($"- Parents: {string.Join(", ", e.Parents.Select(Code))}");
                if (e.Spec.Count > 0)
                    md.AppendLine($"- Specification: {Refs(e.Spec)}");
                md.AppendLine();
            }
            md.AppendLine("`!` marks required attributes.");
        }
        return md.ToString();
    }

    static string PresetPage(CatalogData data)
    {
        var md = new StringBuilder();
        md.AppendLine("# Preset geometries");
        md.AppendLine();
        md.AppendLine("From `presetShapeDefinitions.xml` and `presetTextWarpDefinitions.xml` (ECMA-376 Part 1). Every preset is defined");
        md.AppendLine("by adjust values, guide formulas, handles, connection sites and paths, so a renderer can evaluate all of them");
        md.AppendLine("with one formula engine instead of hand-written code per shape.");
        md.AppendLine();
        AppendCheck(md, "a:ST_ShapeType", data.ShapeTypeValues, data.PresetShapes);
        AppendCheck(md, "a:ST_TextShapeType", data.TextShapeTypeValues, data.TextWarps);
        foreach (var (title, list) in new[] { ("Shapes", data.PresetShapes), ("Text warps", data.TextWarps) })
        {
            md.AppendLine($"## {title} ({list.Count})");
            md.AppendLine();
            md.AppendLine("| Name | Adjust values | Guides | Handles | Connection sites | Paths |");
            md.AppendLine("|---|---:|---:|---:|---:|---:|");
            foreach (var p in list)
                md.AppendLine($"| `{p.Name}` | {p.AdjustValues} | {p.Guides} | {p.Handles} | {p.ConnectionSites} | {p.Paths} |");
            md.AppendLine();
        }
        return md.ToString();
    }

    static void AppendCheck(StringBuilder md, string simpleType, List<string> values, List<PresetGeometry> presets)
    {
        var names = presets.Select(p => p.Name).ToList();
        var findings = new List<string>();
        if (values.Except(names).ToList() is { Count: > 0 } missing)
            findings.Add($"no definition for {string.Join(", ", missing.Select(Code))}");
        if (names.Distinct().Except(values).ToList() is { Count: > 0 } extra)
            findings.Add($"definitions not listed in the type: {string.Join(", ", extra.Select(Code))}");
        if (names.GroupBy(n => n).Where(g => g.Count() > 1).Select(g => g.Key).ToList() is { Count: > 0 } twice)
            findings.Add($"defined twice: {string.Join(", ", twice.Select(Code))}");

        md.Append($"- `{simpleType}` lists {values.Count} values, the data file has {names.Count} definitions");
        md.AppendLine(findings.Count == 0 ? "; they match." : ": " + string.Join("; ", findings) + ".");
        md.AppendLine();
    }

    static string FieldCodePage(CatalogData data)
    {
        var md = new StringBuilder();
        md.AppendLine("# Field codes");
        md.AppendLine();
        md.AppendLine("Field instructions are plain text inside `w:instrText` / `w:fldSimple/@w:instr`, so the schemas do not show them.");
        md.AppendLine("Syntax, switches and formulas: ECMA-376 Part 1, §17.16.1 to §17.16.4.");
        md.AppendLine();
        md.AppendLine("| Field | Section | Page | MS-OI29500 |");
        md.AppendLine("|---|---|---:|---|");
        foreach (var f in data.Spec.FieldCodes)
        {
            var notes = data.Spec.OfficeNotes.Where(n => n.Part == 1 && n.IsoSection == f.Section).Select(n => n.Section);
            md.AppendLine($"| `{f.Name}` | §{f.Section} | {f.Page} | {string.Join(", ", notes)} |");
        }
        return md.ToString();
    }

    static string Defined(List<string> values, List<PresetGeometry> presets) =>
        $"{values.Count(v => presets.Any(p => p.Name == v))} with a geometry definition";

    static bool IsExtension(NamespaceEntry ns) => ns.Uri.StartsWith("http://schemas.microsoft.com/", StringComparison.Ordinal);

    static string Refs(List<SpecRef> refs) => string.Join("; ", refs.Select(r =>
    {
        var doc = r.Doc switch { "ECMA-376-1" => "", "ECMA-376-4" => "Part 4 ", _ => r.Doc + " " };
        var notes = r.OfficeNotes is { Count: > 0 } n ? $", OI {string.Join(", ", n)}" : "";
        return $"{doc}§{r.Section} p.{r.Page}{notes}";
    }));

    static string Values(List<string> values) =>
        values.Count <= 12
            ? string.Join(", ", values.Select(Code))
            : string.Join(", ", values.Take(12).Select(Code)) + $" … (+{values.Count - 12})";

    static string Version(string? version) => version switch
    {
        null => "?",
        "Microsoft365" => "M365",
        _ when version.StartsWith("Office", StringComparison.Ordinal) => version["Office".Length..],
        _ => version,
    };

    static string Code(string s) => s.StartsWith('(') ? s : $"`{s}`";
    static string Cell(string s) => s.Replace("|", "\\|");
    static string Anchor(string name) => new(name.ToLowerInvariant().Where(ch => char.IsLetterOrDigit(ch) || ch is '-' or '_').ToArray());
    static string N(int n) => n.ToString("N0", CultureInfo.InvariantCulture);
}
